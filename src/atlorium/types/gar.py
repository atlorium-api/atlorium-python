class GarRegionStatsResponse(TypedDict, total=False):
    """Статистика по конкретному региону (субъекту РФ)."""

    regionCode: str
    """Код региона (2 цифры)."""

    regionName: str
    """Наименование региона."""

    addressObjectCount: int
    """Количество адресных объектов в регионе."""

    houseCount: int
    """Количество домов в регионе."""

    apartmentCount: int
    """Количество квартир/помещений в регионе."""

    roomCount: int
    """Количество комнат в регионе."""

    steadCount: int
    """Количество земельных участков в регионе."""

    carplaceCount: int
    """Количество машино-мест в регионе."""

    nonResidentialCount: int
    """
    Количество нежилых помещений: офисы, склады, цеха, торговые залы, павильоны,
    подвалы, котельные, погреба, рабочие участки и помещения без уточнения типа.
    """

    garageCount: int
    """Количество гаражей."""

    unknownTypeCount: int
    """Количество объектов, тип которых в реестре не указан."""

    breakdown: dict[str, int]
    """
    Полная разбивка по каноническим типам объектов: «квартира», «комната»,
    «помещение», «гараж» и так далее, как их отдаёт геокодер.
    """

    totalObjectCount: int
    """Общее количество объектов реестра всех типов в регионе."""

    elapsedMs: int
    """Время выполнения запроса в миллисекундах."""


class GarSearchResult(TypedDict, total=False):
    """
    Один результат поиска адреса в ГАР.
    Содержит полный адрес, идентификаторы и ключевые параметры объекта.
    """

    fullAddress: str
    """
    Полный адрес объекта, построенный из иерархии (PATH).
    Пример: "Самарская обл, г Самара, ул Ленина, д. 5\"
    """

    objectType: str
    """Тип объекта: "адр.объект", "дом", "квартира", "комната", "зем.участок", "машино-место"."""

    objectGuid: str
    """
    UUID (GUID) объекта в ГАР.
    Аналог AOGUID/HOUSEGUID из старого ФИАС.
    """

    objectId: int
    """Числовой идентификатор объекта (стабильный, не меняется при обновлении)."""

    regionCode: str
    """Двузначный код региона (например, "77" = Москва, "63" = Самарская обл.)."""

    postalCode: str
    """Почтовый индекс (6 цифр), если доступен."""

    oktmo: str
    """Код ОКТМО (8 или 11 цифр), если доступен."""

    okato: str
    """Код ОКАТО (до 11 цифр), если доступен."""


class GarSearchResponse(TypedDict, total=False):
    """Ответ на поисковый запрос: список результатов с метаданными."""

    query: str
    """Исходная строка запроса."""

    results: list[GarSearchResult]
    """Список найденных адресных объектов."""

    count: int
    """Количество найденных результатов."""

    elapsedMs: int
    """Время выполнения запроса в миллисекундах."""


