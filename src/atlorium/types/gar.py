"""
Типы запросов и ответов сервиса «ГАР/ФИАС API».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/gar_ru.json.
"""

from __future__ import annotations

from typing import TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


class GarChildItem(TypedDict, total=False):
    """Дочерний объект (дом, квартира, земельный участок и т.д.)."""

    objectId: int
    """Числовой идентификатор."""

    objectGuid: str
    """UUID (GUID) объекта."""

    displayName: str
    """Отображаемое имя (например, "д. 5 корп. 1", "кв. 18")."""

    objectType: str
    """Тип объекта ("дом", "квартира", "комната", "зем.участок", "машино-место", "адр.объект")."""

    houseType: str
    """
    Тип объекта из справочника ГАР AS_HOUSE_TYPES, краткой формой:
    «д.» (дом), «гар.» (гараж), «влд.» (владение), «зд.» (здание),
    «д.влд.» (домовладение). Пусто у участков, машино-мест, помещений и
    адресообразующих объектов — у них своего справочника типов нет.
    """

    postalCode: str
    """Почтовый индекс (если доступен, для домов)."""


class GarChildrenResponse(TypedDict, total=False):
    """Ответ со списком дочерних объектов."""

    parentObjectId: int
    """Идентификатор родительского объекта."""

    children: list[GarChildItem]
    """Список дочерних объектов."""

    count: int
    """Общее количество дочерних объектов."""

    elapsedMs: int
    """Время выполнения запроса в миллисекундах."""


class GarHierarchyItem(TypedDict, total=False):
    """Элемент иерархии адреса (один уровень пути от объекта к региону)."""

    objectId: int
    """Числовой идентификатор объекта."""

    displayName: str
    """Отображаемое имя объекта (например, "ул Ленина", "д. 5")."""


class GarHierarchyResponse(TypedDict, total=False):
    """Ответ с иерархией объекта (путь от корня до объекта)."""

    objectId: int
    """Идентификатор запрошенного объекта."""

    path: list[GarHierarchyItem]
    """Путь в иерархии от корня (региона) к объекту."""

    elapsedMs: int
    """Время выполнения запроса в миллисекундах."""


class GarParamEntry(TypedDict, total=False):
    """Параметр объекта ГАР (индекс, ОКТМО, ОКАТО, КЛАДР, ИФНС и т.д.)."""

    typeId: int
    """Тип параметра (числовой идентификатор из справочника AS_PARAM_TYPES)."""

    typeName: str
    """Расшифровка типа параметра (например, "Почтовый индекс", "ОКТМО")."""

    value: str
    """Значение параметра (строка, формат зависит от типа)."""


class GarObjectDetailsResponse(TypedDict, total=False):
    """Детальная информация об одном объекте ГАР."""

    objectId: int
    """Числовой идентификатор объекта."""

    objectGuid: str
    """UUID (GUID) объекта."""

    fullAddress: str
    """Полный адрес объекта (из иерархии)."""

    objectType: str
    """Тип объекта."""

    regionCode: str
    """Код региона (2 цифры)."""

    hierarchy: list[GarHierarchyItem]
    """Иерархия: путь от корня (региона) к данному объекту."""

    parameters: list[GarParamEntry]
    """
    Параметры объекта (индекс, ОКТМО, ОКАТО, ИФНС, КЛАДР и т.д.).
    Параметры наследуются от предков, если у объекта своих нет.
    """

    elapsedMs: int
    """Время выполнения запроса в миллисекундах."""


