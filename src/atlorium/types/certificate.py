"""
Типы запросов и ответов сервиса «API проверки SSL-сертификата».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/certificate_ru.json.
"""

from __future__ import annotations

from typing import TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


class CertificateChainItem(TypedDict, total=False):
    """
    Одно звено цепочки доверия: сертификат сайта, промежуточный сертификат удостоверяющего
    центра или корневой. Звенья идут от сертификата сайта к корню.
    """

    subject: str
    """Владелец этого звена цепочки в виде отличительного имени (DN)."""

    issuer: str
    """
    Кто выпустил это звено. У корневого сертификата совпадает с subject —
    корень подписывает сам себя, и на нём цепочка заканчивается.
    """

    validFrom: str
    """Начало срока действия звена (UTC)."""

    validTo: str
    """
    Окончание срока действия звена (UTC). Промежуточный сертификат вполне может истечь
    раньше сертификата сайта — тогда соединение сломается, хотя сам сертификат сайта ещё годен.
    """

    thumbprint: str
    """Отпечаток звена — хеш в шестнадцатеричном виде."""

    isValid: bool
    """Годно ли это конкретное звено. Негодное звено делает недоверенной всю цепочку."""

    errors: list[str]
    """Претензии к этому звену, если оно признано негодным."""


class CertificateData(TypedDict, total=False):
    """
    Результат проверки SSL/TLS-сертификата одного хоста: срок действия, кто выдал, для каких
    доменов годится, параметры ключа и цепочка доверия.
    """

    isValid: bool
    """
    Главный вердикт: годен ли сертификат прямо сейчас. true — срок не истёк,
    цепочка доверия выстроилась и имя хоста сертификату соответствует. При false
    конкретные претензии перечислены в errors.
    """

    expirationDate: str
    """
    Дата и время (UTC) окончания срока действия. После этого момента браузеры и
    HTTP-клиенты начнут показывать предупреждение о небезопасном соединении.
    """

    daysRemaining: int
    """
    Сколько суток осталось до expirationDate. Отрицательное значение
    означает, что срок уже истёк: −3 — сертификат просрочен три дня назад.
    Именно по этому полю удобно строить мониторинг: тревога при значении ниже 14.
    """

    issuer: str
    """
    Удостоверяющий центр, выпустивший сертификат, в виде отличительного имени (DN).
    Пример: CN=R11, O=Let's Encrypt, C=US.
    """

    subject: str
    """
    Владелец сертификата в виде отличительного имени (DN). У бесплатных сертификатов
    это обычно только домен: CN=example.com. У сертификатов с проверкой
    организации сюда попадают ещё название компании и страна.
    """

    subjectAlternativeNames: list[str]
    """
    Полный список доменов, которые покрывает сертификат (расширение SAN). Именно он,
    а не subject, определяет, для каких имён сертификат действителен.
    Может содержать маски: example.com, www.example.com, *.api.example.com.
    """

    errors: list[str]
    """
    Причины, по которым сертификат признан негодным: истёкший срок, несовпадение имени
    хоста, разрыв цепочки доверия, самоподписанность. Пустой список при
    isValid = true.
    """

    tlsVersion: str
    """
    Версия протокола, на которой удалось согласовать соединение: Tls13,
    Tls12 и т.д. Версии ниже TLS 1.2 считаются устаревшими и небезопасными.
    """

    validFrom: str
    """Дата и время (UTC) начала срока действия — с этого момента сертификат годен."""

    serialNumber: str
    """
    Серийный номер, присвоенный удостоверяющим центром. Уникален в пределах этого центра;
    по нему сертификат ищут в списках отзыва и в журналах Certificate Transparency.
    """

    thumbprint: str
    """
    Отпечаток — хеш сертификата в шестнадцатеричном виде. Однозначно идентифицирует
    конкретный сертификат: если между двумя проверками отпечаток изменился, сертификат
    перевыпустили или подменили.
    """

    signatureAlgorithm: str
    """
    Алгоритм подписи сертификата, например sha256RSA. Подпись на устаревшем
    SHA-1 современные браузеры отвергают.
    """

    publicKeyAlgorithm: str
    """Алгоритм открытого ключа: RSA или ECDSA."""

    keySize: int
    """
    Длина ключа в битах. Сравнивать значения разных алгоритмов напрямую нельзя:
    у RSA приемлемый минимум — 2048, а у ECDSA 256 бит дают сопоставимую стойкость.
    """

    hasPrivateKey: bool
    """
    Есть ли рядом с сертификатом закрытый ключ. При проверке чужого сайта здесь всегда
    false: закрытый ключ наружу не отдаётся никогда и никем — это была бы полная
    компрометация сертификата.
    """

    isSelfSigned: bool
    """
    Сертификат подписан сам собой, а не удостоверяющим центром. Такие сертификаты
    нормальны во внутренней сети и на тестовых стендах, но для публичного сайта означают,
    что посетитель увидит предупреждение браузера.
    """

    certificateChain: list[CertificateChainItem]
    """
    Цепочка доверия от сертификата сайта к корневому сертификату. Разрыв в цепочке —
    частая причина ошибки в браузере при формально живом сертификате: сервер забыли
    настроить отдавать промежуточный сертификат.
    """

    connectionTime: str
    """
    Сколько заняло установление TLS-соединения. Косвенно показывает удалённость сервера
    и его нагруженность; на вердикт не влияет.
    """

    host: str
    """Проверенный хост — доменное имя или IP-адрес."""

    port: int
    """Проверенный порт. По умолчанию 443; у почтовых и иных служб бывает свой."""

    checkedAt: str
    """
    Момент, на который актуален результат проверки. По нему видно, насколько свежи
    сведения о сертификате; если нужен заведомо актуальный результат, есть режим
    принудительной перепроверки.
    """


__all__ = ["ApiError", "CertificateChainItem", "CertificateData"]
