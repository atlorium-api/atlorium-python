"""
Типы запросов и ответов сервиса «API анализа изображения».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/imagecheck_ru.json.
"""

from __future__ import annotations

from typing import Literal, TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


ImageFlagSource = Literal["safe_search", "label", "text"]
"""
Какой слой анализа дал срабатывание. Поле нужно не для отчётности:
от слоя зависит, что модератору смотреть. Срабатывание по тексту
показывает саму надпись, срабатывание по метке — что на изображении,
срабатывание классификатора — категорию и её степень.

Значения:
* `SafeSearch` — Классификация содержимого: нагота, откровенность, насилие, медицина, подделка.
* `Label` — Метка предмета или сюжета, попавшая в стоп-лист.
* `Text` — Слово или выражение из словаря, найденное в тексте НА изображении.
"""


class ImageLabel(TypedDict, total=False):
    """Одна распознанная метка: что изображено и насколько уверенно."""

    name: str
    """Название на английском — так его возвращает классификатор."""

    nameRu: str | None
    """
    Русское название, если метка есть в нашем словаре перевода; иначе null.
    Поле необязательное: словарь охватывает частотные метки, а не весь набор.
    """

    score: float
    """Уверенность от 0 до 1. Значения ниже 0,5 в ответ не попадают."""


ImageLikelihood = Literal["unknown", "very_unlikely", "unlikely", "possible", "likely", "very_likely"]
"""
Степень уверенности классификатора. Порядок значений — от «почти наверняка
нет» к «почти наверняка да», и на этот порядок опирается сравнение с порогом
срабатывания: значение считается сработавшим, если оно не меньше порога.

Значения:
* `Unknown` — Оценка не получена — признак не проверялся или ответ не содержал её.
* `VeryUnlikely` — Почти наверняка нет.
* `Unlikely` — Скорее нет.
* `Possible` — Возможно. Пограничное значение: именно с него обычно начинают ручной разбор.
* `Likely` — Скорее да.
* `VeryLikely` — Почти наверняка да.
"""

ImageModerationDecision = Literal["allow", "review", "block"]
"""
Сводное решение по изображению. Три значения вместо двух — осознанный выбор:
автоматическое удаление по одному лишь машинному признаку даёт ложные
срабатывания на медицинских, исторических и новостных материалах, а полностью
ручная модерация не справляется с объёмом. Промежуточное
review отделяет «однозначно нельзя» от «нужен человек».

Значения:
* `Allow` — Ничего из запрещённого не найдено — изображение можно публиковать.
* `Review` — Есть основания для сомнений: показать модератору, а не удалять автоматически.
* `Block` — Сработал признак высокой степени — публиковать без разбора нельзя.
"""


class ImageModerationFlag(TypedDict, total=False):
    """Одно срабатывание фильтра — то, ради чего сервис существует."""

    category: str
    """
    Категория нарушения — ключ из файла стоп-листов (например, drugs,
    weapons, gambling, extremism, adult).
    Набор категорий редактируется без перевыкатки приложения, поэтому
    неизвестное значение клиентский код должен переносить спокойно.
    """

    title: str
    """Человекочитаемое название категории на русском."""

    source: ImageFlagSource
    """Каким слоем анализа получено срабатывание."""

    evidence: str
    """
    Что именно сработало: распознанная метка, найденное в тексте выражение
    или название категории классификатора. Это и показывают модератору.
    """

    severity: ImageModerationDecision
    """
    Решение, которого требует ЭТО срабатывание. Итоговое решение по
    изображению — самое строгое из всех срабатываний.
    """


class ImageModerationRequest(TypedDict, total=False):
    """Запрос на анализ одного изображения."""

    image: str
    """
    Изображение в кодировке Base64 — «голым» base64 или data-URL вида
    data:image/jpeg;base64,.... Обязательное поле. Предел — 7 МБ
    в декодированном виде; фотография с телефона укладывается с запасом.
    Число нецелое не случайно: картинка уезжает в base64 внутри JSON-запроса,
    у которого чужой потолок 10 МБ, а кодирование добавляет около 37 %.
    Принимаются растровые форматы (JPEG, PNG, WEBP, BMP, GIF); PDF и видео
    на вход не подаются.
    """

    includeText: bool
    """
    Читать текст НА изображении и сверять его со словарём запрещённых
    выражений. Включено по умолчанию, и отключать это стоит с открытыми
    глазами.

    ⚠️ Что перестаёт ловиться при false: скриншот с контактом продавца
    запрещённого, баннер казино, объявление о продаже документов,
    экстремистский лозунг поверх нейтральной картинки. На таких изображениях
    НЕ срабатывают ни классификация содержимого, ни метки предметов —
    там нет ни наготы, ни насилия, ни узнаваемого предмета. Текстовый слой
    для них единственный. В российских реалиях на него приходится
    значительная доля всего, что подлежит удалению.

    Добавляет ОДНУ единицу работы. Отсутствие текста на изображении —
    нормальный исход, он тарифицируется: работа по чтению выполнена.
    """

    includeWebSearch: bool
    """
    Добавить поиск изображения в вебе: где ещё встречается эта картинка
    и какие страницы её содержат. Полезно против украденных фотографий
    в объявлениях и против контрафакта.

    Самый дорогой из слоёв, поэтому выключен по умолчанию. Добавляет ОДНУ
    единицу работы. Если поиск не дал совпадений, единица за него
    не списывается — платить за пустой ответ клиент не должен.
    """


class ImageSafeSearch(TypedDict, total=False):
    """
    Результат классификации содержимого — пять независимых категорий.
    Каждая оценивается отдельно: изображение может быть одновременно
    безобидным по одной категории и пограничным по другой.
    """

    adult: ImageLikelihood
    """Нагота, порнография."""

    racy: ImageLikelihood
    """Откровенные позы, полупрозрачная одежда, провокационность без наготы."""

    violence: ImageLikelihood
    """Насилие, кровь, увечья."""

    medical: ImageLikelihood
    """
    Медицинское изображение. Само по себе не нарушение: попадает в ответ,
    потому что медицинский снимок часто ошибочно принимают за насилие,
    и модератору полезно видеть эту пометку рядом.
    """

    spoof: ImageLikelihood
    """Изображение изменено, чтобы выглядеть смешно или оскорбительно."""


class ImageWebMatch(TypedDict, total=False):
    """Одно совпадение изображения в вебе."""

    pageUrl: str
    """Адрес страницы, на которой встречается это изображение."""

    fullMatch: bool
    """
    true — на странице найдена ровно эта картинка; false — визуально похожая
    (обрезанная, перекрашенная, с водяным знаком). Полное совпадение —
    признак прямого заимствования, частичное требует глазами.
    """


class ImageWebSearch(TypedDict, total=False):
    """
    Результат поиска изображения в вебе. Приходит, только если запрошен
    параметром includeWebSearch.
    """

    fullMatchCount: int
    """Сколько страниц содержат ровно это изображение."""

    partialMatchCount: int
    """Сколько страниц содержат визуально похожее изображение."""

    bestGuess: str | None
    """
    Наиболее вероятное описание изображения по данным веба — иногда точнее
    меток, потому что учитывает подписи на страницах. Может отсутствовать.
    """

    matches: list[ImageWebMatch]
    """Найденные страницы, полные совпадения первыми. Не больше десяти."""


class ImageModerationResult(TypedDict, total=False):
    """Полный результат анализа изображения."""

    decision: ImageModerationDecision
    """Сводное решение: публиковать, показать модератору или не публиковать."""

    flags: list[ImageModerationFlag]
    """
    Все сработавшие фильтры, самые строгие первыми. Пустой список при
    allow — нормальное и частое состояние.
    """

    safeSearch: ImageSafeSearch
    """Слой 1: классификация содержимого по пяти категориям."""

    labels: list[ImageLabel]
    """
    Слой 2: что изображено. Отсортировано по убыванию уверенности,
    не больше двадцати меток.
    """

    text: str
    """
    Слой 3: текст, найденный НА изображении, одной строкой с сохранением
    переносов. Пустая строка означает либо что читаемого текста нет, либо
    что слой не заказывался (includeText=false) — ни то ни другое
    не ошибка и не повод для повторного запроса. Какой именно случай
    перед вами, видно по billedUnits.
    """

    webSearch: ImageWebSearch | None
    """
    Результат поиска в вебе. null, если поиск не запрашивался ИЛИ
    не дал совпадений; во втором случае единица за него не списывается.
    """

    billedUnits: int
    """
    Сколько единиц работы фактически списано за этот запрос — от одной до трёх.

    Одна — обязательный базовый слой: метки предметов плюс классификация
    содержимого (она выполняется вместе с метками и отдельной единицей
    не считается). Вторая — чтение текста на изображении, если оно заказано.
    Третья — поиск в вебе, и только если он вернул совпадения.

    Поле возвращается, чтобы расход можно было сверить, не заглядывая
    в биллинг, и чтобы разница между заказанным и списанным была видна
    сразу: слой, не вернувший данных, работой не является.
    """

    elapsedMs: int
    """Время обработки на нашей стороне, миллисекунды."""

    message: str
    """
    Пояснение к результату, когда оно есть: например, что часть слоёв
    не отработала и решение принято по остальным. Обычно пустая строка.
    """


