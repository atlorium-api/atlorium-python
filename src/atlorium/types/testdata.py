"""
Типы запросов и ответов сервиса «API генератора тестовых данных РФ».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/testdata_ru.json.
"""

from __future__ import annotations

from typing import Literal, TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


class TestDataFieldDescriptor(TypedDict, total=False):
    """
    Описание одного типа данных (поля), который умеет генерировать сервис: идентификатор
    для запроса, название, пояснение, смысловая группа и пример значения.
    """

    id: str
    """
    Технический идентификатор поля — то, что клиент передаёт в запросе и что становится
    ключом в JSON-записи и заголовком колонки CSV. Например innPerson.
    """

    title: str
    """Название поля по-русски."""

    titleEn: str
    """Название поля по-английски."""

    description: str
    """Пояснение: что именно в поле и как оно устроено."""

    descriptionEn: str
    """То же по-английски."""

    group: str
    """
    Смысловая группа поля, по которой поля удобно группировать при выборе:
    «Персона», «Налоговые реквизиты», «Банк», «Документы», «Контакты», «Адрес», «Организация», «Транспорт».
    """

    hasChecksum: bool
    """
    true, если у значения есть рассчитываемый контрольный разряд (ИНН, СНИЛС, ОГРН,
                счёт, номер карты, VIN) — такое значение пройдёт проверку контрольной суммы в вашей системе.
    """

    sample: str
    """Пример значения этого поля."""


TestDataGender = Literal["any", "male", "female"]
"""
Пол сгенерированной персоны. Определяет согласование имени, отчества и фамилии между собой.

Значения:
* `Any` — Пол выбирается случайно для каждой записи.
* `Male` — Все записи — мужские: имя, отчество и фамилия согласованы в мужском роде.
* `Female` — Все записи — женские: имя, отчество и фамилия согласованы в женском роде.
"""


class TestDataRequest(TypedDict, total=False):
    """Запрос на генерацию тестовых данных."""

    count: int
    """
    Сколько записей сгенерировать. Допустимо от 1 до maxCount.
    Значение по умолчанию — 1.
    """

    seed: int | None
    """
    Начальное значение генератора случайных чисел. Одинаковый seed при одинаковом наборе
    полей и количестве записей даёт побайтово одинаковый результат — на этом строятся
    стабильные автотесты.
    """

    fields: list[str] | None
    """
    Список полей, которые нужно сгенерировать (идентификаторы из каталога
    TestDataFields). Пустой список или null — будет использован
    набор по умолчанию default.
    """

    gender: TestDataGender
    """
    Пол генерируемых персон: any (по умолчанию), male или female.
    Влияет только на поля персоны — имя, отчество, фамилию, обращение и производные
    от них логин и почту.
    """

    format: str | None
    """
    Формат ответа: json (по умолчанию) или csv.
    Значения из TestDataFormats.
    """


class TestDataResponse(TypedDict, total=False):
    """Ответ сервиса в формате JSON."""

    seed: int
    """
    Начальное значение генератора, фактически использованное при построении выдачи.
    Совпадает с переданным в запросе либо выбрано сервисом, если клиент его не задал.
    Передайте это же значение, чтобы получить точно такой же результат снова.
    """

    count: int
    """Количество записей в records."""

    fields: list[str]
    """Идентификаторы полей в порядке следования — он же порядок колонок в CSV."""

    records: list[dict[str, str]]
    """
    Сгенерированные записи. Каждая запись — словарь «идентификатор поля → значение».
    Все значения строковые: тестовые данные почти всегда идут дальше как текст (в CSV,
    в форму, в SQL-скрипт), и единый строковый тип избавляет клиента от разбора
    разнотипного JSON.
    """

    disclaimer: str
    """
    Напоминание о характере данных, которое едет вместе с каждым ответом. Оставлено в
    контракте намеренно: если выгрузка окажется в чужих руках или попадёт в лог, из неё
    самой должно быть видно, что это вымышленные данные для тестирования.
    """


__all__ = ["ApiError", "TestDataFieldDescriptor", "TestDataGender", "TestDataRequest", "TestDataResponse"]
