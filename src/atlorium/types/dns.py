"""
Типы запросов и ответов сервиса «API проверки DNS».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/dns_ru.json.
"""

from __future__ import annotations

from typing import TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


class DnsRecordEntry(TypedDict, total=False):
    """
    Одна DNS-запись в едином виде — независимо от того, какого она типа.
    Значение всегда лежит в value, а специфичные для типа детали —
    в preference и details.
    """

    name: str
    """
    Имя, к которому относится запись. Обычно совпадает с запрошенным доменом, но
    у поддоменов и почтовых записей отличается: mail.example.com.
    """

    value: str
    """
    Значение записи. Что именно в нём лежит, зависит от типа: у A — IPv4-адрес
    (93.184.216.34), у AAAA — IPv6, у MX — имя почтового сервера,
    у TXT — произвольная строка, у CNAME и NS — доменное имя.
    """

    ttl: int | None
    """
    Время жизни записи в секундах — сколько её разрешено держать в кэше. Маленькое
    значение (60–300) обычно ставят перед переездом, чтобы изменения разошлись быстро.
    null — если резолвер не сообщил TTL.
    """

    preference: int | None
    """
    Приоритет записи MX: чем МЕНЬШЕ число, тем выше приоритет почтового сервера.
    Для остальных типов записей — null.
    """

    details: str | None
    """
    Дополнительные сведения по записи в свободной форме, если тип записи их подразумевает.
    null — если добавить нечего.
    """


class DnsRecordGroup(TypedDict, total=False):
    """
    Записи одного типа, сложенные вместе. У домена почти всегда несколько записей одного
    типа — например, два адреса A или три почтовых сервера MX.
    """

    type: str
    """
    Тип записей в группе: A (адрес IPv4), AAAA (адрес IPv6),
    MX (почтовый сервер), TXT (текст: SPF, DKIM, проверки владения),
    CNAME (псевдоним), NS (управляющие DNS-серверы домена).
    """

    records: list[DnsRecordEntry]
    """Сами записи. Пустой список означает, что записей такого типа у домена нет."""


class DnsLookupResponse(TypedDict, total=False):
    """Результат обычной проверки DNS — ответ одного резолвера по одному домену."""

    domain: str
    """Проверенное доменное имя."""

    resolver: str
    """
    Резолвер, ответивший на запрос: адрес или узнаваемое имя публичного DNS-сервиса
    (например, Google или Cloudflare).
    """

    requestedAtUtc: str
    """
    Момент выполнения запроса (UTC). Полезен как отметка времени: DNS меняется, и без неё
    сохранённый ответ невозможно соотнести с состоянием домена.
    """

    records: list[DnsRecordGroup]
    """Найденные записи, сгруппированные по типу."""

    errors: list[str]
    """
    Ошибки резолва: домен не существует, таймаут, отказ сервера. Пустой список —
    запрос отработал полностью. Непустой список не отменяет уже найденные записи
    в records: часть типов могла разрешиться, часть — нет.
    """


class DnsResolverSnapshot(TypedDict, total=False):
    """Ответ одного резолвера в проверке распространения."""

    label: str
    """Узнаваемое имя резолвера для показа человеку: «Google», «Cloudflare», «Yandex»."""

    resolver: str
    """Адрес резолвера, к которому фактически обращались."""

    durationMs: int
    """
    Сколько миллисекунд занял ответ этого резолвера. Заметно большее значение на фоне
    остальных обычно означает не проблему домена, а удалённость самого резолвера.
    """

    success: bool
    """
    Ответил ли резолвер успешно. При false причина лежит в error,
    а records будет пустым — учитывать такой снимок при сравнении значений нельзя.
    """

    error: str | None
    """Причина неудачи, если резолвер не ответил. null — при успехе."""

    records: list[DnsRecordGroup]
    """Записи, которые вернул именно этот резолвер."""


class DnsPropagationResponse(TypedDict, total=False):
    """
    Отчёт о распространении (propagation): один и тот же домен спрошен у нескольких
    резолверов сразу.

    Смысл проверки — увидеть, разошлись ли изменения по миру. Сразу после правки записей
    часть резолверов отдаёт новое значение, а часть ещё держит в кэше старое, и выглядит
    это как «у меня сайт открывается, а у клиента нет».
    """

    domain: str
    """Проверенное доменное имя."""

    requestedAtUtc: str
    """Момент выполнения запроса (UTC)."""

    snapshots: list[DnsResolverSnapshot]
    """
    Ответы отдельных резолверов. Расхождение значений между снимками и означает,
    что изменения ещё не разошлись.
    """


