"""
Типы запросов и ответов сервиса «API проверки ссылки».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/urlcheck_ru.json.
"""

from __future__ import annotations

from typing import Literal, TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


UrlThreatType = Literal["malware", "social_engineering", "unwanted_software"]
"""
Категория угрозы, найденной по ссылке. Значений немного и они не пересекаются: одна и та же
ссылка может попасть сразу в несколько категорий, поэтому в ответе лежит СПИСОК, а не одно
значение.

Значения:
* `Malware` — Вредоносное ПО: страница пытается установить на устройство посетителя программу, действующую против его интересов, — троян, шифровальщик, майнер.
* `SocialEngineering` — Социальная инженерия — то, что в быту называют фишингом: страница притворяется чужой (банком, госпорталом, маркетплейсом, страницей входа) и выманивает пароли, коды подтверждения или реквизиты карты. Самая частая категория в русскоязычном сегменте.
* `UnwantedSoftware` — Нежелательное ПО: формально не вирус, но ведёт себя нечестно — подменяет поиск, ставит расширения без спроса, показывает рекламу поверх чужих сайтов, не удаляется штатными средствами.
"""

UrlThreatVerdict = Literal["clean", "threat", "unknown"]
"""
Итог проверки одной ссылки в трёх состояниях. Заводить булево «опасно/не опасно» здесь было
бы ошибкой: третье состояние — «проверить не удалось» — принципиально другое, и путать его
с «чисто» нельзя ни в интерфейсе, ни в биллинге.

Значения:
* `Clean` — Отметок об угрозе в базе на момент проверки нет. Читается вместе с checkedAtUtc: это датированное утверждение, а не гарантия безопасности сайта.
* `Threat` — Ссылка отмечена как опасная. Конкретные категории — в threatTypes.
* `Unknown` — Вердикт получить не удалось — проверка не выполнена. Это НЕ «чисто» и НЕ «опасно» — данных нет вовсе. Такие строки пакета не тарифицируются (см. UrlThreatBatchResponse).
"""


class UrlThreatResult(TypedDict, total=False):
    """Результат проверки ОДНОЙ ссылки."""

    url: str
    """
    Проверенная ссылка в НОРМАЛИЗОВАННОМ виде — так, как она реально уходила на проверку.
    Отличается от присланной клиентом, если тот опустил схему («example.com» → «http://example.com»)
    или оставил лишние пробелы. Возвращаем именно нормализованный вид, чтобы клиент видел,
    что проверялось на самом деле, и не гадал, почему вердикт относится к другому адресу.
    """

    verdict: UrlThreatVerdict
    """Итог проверки: чисто, угроза или «не удалось проверить»."""

    threatTypes: list[UrlThreatType]
    """
    Категории угрозы. Пустой список при clean и
    unknown; при threat —
    одна или несколько категорий (сайт может быть одновременно и фишинговым, и раздающим
    вредонос).
    """

    checkedAtUtc: str
    """
    Момент, к которому относится вердикт (UTC). Именно он превращает «чисто» из обещания в
    датированное утверждение — см. оговорку в шапке файла. Обязателен к показу рядом с
    вердиктом в любом интерфейсе, который строится поверх этого API.
    """

    message: str
    """
    Короткое пояснение для человека: почему такой вердикт и что с ним делать. Заполняется
    всегда, в том числе для «чисто», — интерфейс, показывающий пустоту при благополучном
    исходе, выглядит сломанным.
    """

    elapsedMs: int
    """Сколько миллисекунд заняла проверка. Служебное поле для диагностики интеграции."""


class UrlThreatBatchResponse(TypedDict, total=False):
    """
    Ответ ПАКЕТНОГО режима: по одному UrlThreatResult на каждую присланную ссылку,
    в том же порядке, плюс короткая сводка.
    """

    results: list[UrlThreatResult]
    """Результаты по каждой ссылке — в том же порядке, в каком ссылки пришли в запросе."""

    total: int
    """Сколько ссылок было в пакете (после удаления пустых строк и дубликатов)."""

    threatCount: int
    """Сколько ссылок отмечено как опасные."""

    unknownCount: int
    """
    Сколько ссылок проверить не удалось (вердикт unknown).
    Ровно на это число уменьшается списание относительно размера пакета.
    """

    elapsedMs: int
    """Общее время обработки пакета в миллисекундах."""


