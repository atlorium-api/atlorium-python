"""
Типы запросов и ответов сервиса «API распознавания текста с изображения».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/ocr_ru.json.
"""

from __future__ import annotations

from typing import TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


class ImageOcrRequest(TypedDict, total=False):
    """
    Запрос на распознавание: клиент присылает изображение и режим, получает его содержимое.
    Сценарий синхронный — ответ приходит в том же HTTP-вызове.
    """

    image: str
    """
    Изображение в кодировке Base64 (можно как «голый» base64, так и data-URL вида
    "data:image/png;base64,...."). Обязательное поле. Предел — 10 МБ в декодированном виде:
    скан листа A4 в 300 dpi укладывается с запасом. PDF на вход не принимается —
    многостраничный файл нужно отрендерить в изображения и отправлять постранично.
    """

    mode: str
    """
    Режим распознавания — одно из значений OcrModes. По умолчанию
    auto: сервис сам решает по размеру и содержимому изображения.

    Указывать режим явно стоит в двух случаях: когда автоопределение промахивается на
    нетипичной картинке и когда важна предсказуемая стоимость — короткая строка всегда
    стоит одну единицу работы, а разбор страницы столько, сколько на ней областей.
    """


class ImageOcrResponse(TypedDict, total=False):
    """
    Результат распознавания. recognized = true и text с содержимым —
    успех; recognized = false означает, что читаемого текста на изображении найти
    не удалось. За нераспознанное изображение плата не взимается.
    """

    recognized: bool
    """true, если изображение распознано и в text лежит его содержимое."""

    text: str | None
    """
    Содержимое изображения (при recognized = true); иначе null. Как его
    разбирать — сообщает format.
    """

    format: str
    """
    Формат поля text — одно из значений OcrTextFormats. Значение
    позволяет выбрать разбор, не угадывая его по содержимому: список допустимых значений
    может пополниться, поэтому неизвестное значение разумно обрабатывать как
    plain.
    """

    mode: str
    """
    Режим, в котором изображение РЕАЛЬНО распознано. Совпадает с запрошенным, кроме случая
    auto, где здесь виден выбор сервиса.

    Поле диагностическое и важное: если результат оказался не тем, что ожидалось, первым
    делом надо смотреть сюда — почти всегда причина в том, что автоопределение приняло
    страницу за строку или наоборот, и лечится это явным указанием режима.
    """

    units: int
    """
    Единицы работы, в которые обошёлся запрос, — по ним он и тарифицирован. Короткая строка
    это всегда 1; страница документа — столько, сколько на ней распознано областей
    (заголовки, блоки текста, таблицы). Плотный документ дороже простого ровно во столько
    раз, во сколько больше в нём областей.

    Значение возвращается ВСЕГДА, включая нераспознанные изображения (там оно равно нулю) —
    чтобы расход по пакету можно было сверить, не заглядывая в личный кабинет.
    """

    truncated: bool
    """
    true, если ответ ОБОРВАН и содержимое распознано НЕ ПОЛНОСТЬЮ: упёрлись в предел длины
    ответа или в потолок числа областей на странице.

    Проверять это поле важно: обрезанный текст выглядит совершенно нормальным, и без явного
    признака потеря части документа проходит незамеченной. Практическая реакция — отправить
    страницу на ручную проверку, а не использовать результат как полный.
    """

    elapsedMs: int
    """
    Время обработки запроса в миллисекундах — включая ожидание в очереди, а не только само
    распознавание. Именно поэтому по нему удобно подбирать степень параллелизма пакетной
    обработки: значение растёт при неизменных изображениях — конвейер упёрся в пропускную
    способность сервиса, и увеличивать число потоков дальше бессмысленно.
    """


__all__ = ["ApiError", "ImageOcrRequest", "ImageOcrResponse"]
