"""
Типы запросов и ответов сервиса «API аудита сайта».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/pagespeed_ru.json.
"""

from __future__ import annotations

from typing import Literal, TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


MetricRating = Literal["good", "needs_improvement", "poor", "unknown"]
"""
Качественная оценка одной метрики по общепринятым порогам: «хорошо», «нужно улучшить»,
«плохо». Пороги заданы отраслевой спецификацией метрик, а не этим сервисом, — поэтому
границы и цвета совпадут с любым другим инструментом измерения.

Значения:
* `Good` — Значение в пределах хорошего порога.
* `NeedsImprovement` — Значение между хорошим и плохим порогом: работает, но заметно посетителю.
* `Poor` — Значение хуже плохого порога.
* `Unknown` — Оценки нет: метрика не измерена либо порогов для неё не определено.
"""


class SiteFieldMetric(TypedDict, total=False):
    """Одна метрика ПОЛЕВЫХ данных — то, что видят реальные посетители."""

    key: str
    """Устойчивый машинный ключ метрики («largest_contentful_paint»)."""

    title: str
    """Человеко-читаемое название метрики."""

    percentile: float
    """
    Значение 75-го перцентиля. Для метрик времени — миллисекунды; для сдвига макета —
    безразмерная величина в сотых долях (в
    displayValue она уже приведена к привычному виду).
    """

    displayValue: str
    """Готовое к показу значение с единицей измерения."""

    rating: MetricRating
    """Качественная оценка по общепринятым порогам."""

    goodPercent: float
    """Доля посещений с «хорошим» значением метрики, проценты 0–100."""

    needsImprovementPercent: float
    """Доля посещений со значением «нужно улучшить», проценты 0–100."""

    poorPercent: float
    """Доля посещений с «плохим» значением метрики, проценты 0–100."""


class SiteFieldData(TypedDict, total=False):
    """Полевые данные одного объекта наблюдения — либо конкретной страницы, либо сайта целиком."""

    scope: str
    """
    Что именно описывают эти данные: конкретную страницу («page») или сайт целиком
    («origin»). Различие принципиально: у редко посещаемой страницы своих данных обычно нет,
    а по сайту целиком они есть почти всегда — и подменять одно другим молча нельзя.
    """

    overallRating: MetricRating
    """Сводная оценка объекта наблюдения по совокупности метрик."""

    metrics: list[SiteFieldMetric]
    """Метрики полевых данных."""


class SiteLabMetric(TypedDict, total=False):
    """Одна лабораторная метрика прогона."""

    key: str
    """
    Устойчивый машинный ключ метрики («largest-contentful-paint», «total-blocking-time»).
    Именно по нему стоит писать разбор ответа: заголовок локализуется и меняется, ключ — нет.
    """

    title: str
    """Человеко-читаемое название метрики."""

    displayValue: str | None
    """Готовое к показу значение с единицей измерения («2,4 s», «0,05»)."""

    numericValue: float | None
    """
    Числовое значение метрики — для собственных графиков и порогов. Единица измерения — в
    unit; для метрик времени это миллисекунды, для сдвига макета — безразмерная
    величина.
    """

    unit: str | None
    """Единица измерения числового значения: «ms», «unitless», «byte»."""

    rating: MetricRating
    """Качественная оценка метрики по общепринятым порогам."""


class SiteOpportunity(TypedDict, total=False):
    """Одна рекомендация: что конкретно замедляет страницу и сколько времени даст исправление."""

    key: str
    """Устойчивый машинный ключ рекомендации («render-blocking-resources»)."""

    title: str
    """Название рекомендации."""

    savingsMs: float
    """Оценка выигрыша в миллисекундах, если пункт выполнить."""

    displayValue: str | None
    """Готовое к показу значение выигрыша («Est savings of 1,20 s»)."""


SiteStrategy = Literal["mobile", "desktop"]
"""
Профиль устройства, на котором выполняется прогон. Выбор влияет на результат СИЛЬНО:
мобильный профиль намеренно моделирует небыстрый телефон на медленной сети, и балл на нём
почти всегда заметно ниже настольного. Сравнивать между собой можно только замеры на
ОДНОМ профиле.

Значения:
* `Mobile` — Мобильный профиль — значение по умолчанию. По умолчанию именно он, потому что это профиль, по которому поисковые системы оценивают страницу, и потому что в России доля мобильного трафика выше настольного у подавляющего большинства сайтов.
* `Desktop` — Настольный профиль: быстрое устройство и быстрая сеть.
"""


class SitePerformanceReport(TypedDict, total=False):
    """
    Полный отчёт по одному адресу: оценки по категориям, лабораторные метрики, полевые данные
    (если они есть) и список рекомендаций.
    """

    url: str
    """Адрес, по которому запрашивался аудит (в нормализованном виде)."""

    finalUrl: str
    """
    Адрес, на котором прогон в итоге оказался. Отличается от url при
    переадресации — и это первое, на что стоит смотреть, когда числа выглядят странно:
    возможно, измерялась совсем не та страница (например, редирект увёл на мобильную версию
    или на страницу согласия с cookie).
    """

    strategy: SiteStrategy
    """Профиль устройства, на котором выполнен прогон."""

    fetchedAtUtc: str
    """Момент выполнения прогона (UTC)."""

    performanceScore: int | None
    """
    Балл производительности, 0–100. Это ЛАБОРАТОРНЫЙ показатель, сводящий несколько метрик
    прогона в одно число. null, если категория не запрашивалась.
    """

    accessibilityScore: int | None
    """Балл доступности, 0–100. null, если категория не запрашивалась."""

    bestPracticesScore: int | None
    """Балл соблюдения рекомендуемых практик, 0–100. null, если категория не запрашивалась."""

    seoScore: int | None
    """Балл поисковой оптимизации, 0–100. null, если категория не запрашивалась."""

    labMetrics: list[SiteLabMetric]
    """Лабораторные метрики прогона."""

    fieldData: SiteFieldData | None
    """
    Полевые данные по ЭТОЙ странице. null — данных нет, и это штатный случай для
    малопосещаемых адресов, а не ошибка. В таком случае смотрите
    originFieldData.
    """

    originFieldData: SiteFieldData | None
    """
    Полевые данные по САЙТУ ЦЕЛИКОМ. Есть почти всегда, когда у сайта вообще есть заметный
    трафик, — в том числе когда по конкретной странице данных не набралось.
    """

    opportunities: list[SiteOpportunity]
    """Рекомендации, отсортированные по убыванию оценочного выигрыша."""

    elapsedMs: int
    """Сколько миллисекунд занял аудит на нашей стороне. Служебное поле для диагностики."""

    message: str
    """
    Пояснение для человека: краткий вывод по отчёту. Заполняется всегда — интерфейс,
    показывающий голые цифры без вывода, заставляет клиента интерпретировать их самому.
    """


class SitePerformanceBatchItem(TypedDict, total=False):
    """Одна строка пакетного ответа: либо отчёт, либо причина, по которой отчёта нет."""

    url: str
    """Адрес из запроса (в нормализованном виде)."""

    succeeded: bool
    """Удалось ли выполнить аудит по этому адресу."""

    report: SitePerformanceReport | None
    """Отчёт. Заполнен, когда succeeded = true."""

    error: str | None
    """
    Причина, по которой отчёта нет: страница не открылась, адрес не распознан,
    замер не выполнен. Заполнена, когда succeeded = false.
    """


class SitePerformanceBatchResponse(TypedDict, total=False):
    """Ответ ПАКЕТНОГО режима: по одному элементу на каждый присланный адрес, в том же порядке."""

    results: list[SitePerformanceBatchItem]
    """
    Результаты по каждому адресу — в том же порядке, в каком адреса пришли в запросе.
    Порядок гарантирован: пакет обычно приходит из чужого цикла по своему списку, и
    сопоставление по индексу — самый дешёвый способ разобрать ответ.
    """

    total: int
    """Сколько адресов было в пакете (после удаления пустых строк и дубликатов)."""

    succeededCount: int
    """Сколько адресов удалось проверить. Ровно за столько единиц идёт списание."""

    failedCount: int
    """Сколько адресов проверить не удалось. Эти адреса не тарифицируются."""

    elapsedMs: int
    """Общее время обработки пакета в миллисекундах."""


