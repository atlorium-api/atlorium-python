"""
Типы запросов и ответов сервиса «API проверки почты».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/email_ru.json.
"""

from __future__ import annotations

from typing import Literal, TypedDict


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


EmailStatus = Literal["Valid", "Invalid", "CatchAll", "Unknown", "SpamTrap", "Abuse", "DoNotMail"]
"""
Итоговый вердикт по адресу — семь возможных значений. Исходное строковое значение
вердикта дополнительно возвращается в statusRaw,
чтобы значение, появившееся в будущем, не потерялось при разборе ответа.

Значения:
* `Valid` — Ящик существует и принимает почту. Можно писать.
* `Invalid` — Ящика не существует либо домен не принимает почту. Письмо отскочит (hard bounce).
* `CatchAll` — Домен принимает почту НА ЛЮБОЙ адрес (catch-all), поэтому существование конкретного ящика проверить снаружи невозможно. Не «плохо» и не «хорошо» — неопределённость.
* `Unknown` — Проверить не удалось: почтовый сервер не ответил, применил greylisting или анти-спам. Такой ответ не тарифицируется — платить нужно только за содержательный вердикт.
* `SpamTrap` — Адрес-ловушка для спамеров (spamtrap). Писать нельзя — убьёт репутацию домена.
* `Abuse` — Владелец адреса ранее жаловался на спам (abuse). Писать крайне нежелательно.
* `DoNotMail` — «Не писать»: role-адрес (info@, sales@), одноразовый ящик, токсичный домен или адрес из глобального списка исключений. Технически может работать, но рассылать на него нельзя.
"""


class EmailValidationReport(TypedDict, total=False):
    """
    Карточка проверки одного почтового адреса: вердикт доставляемости и признаки,
    на которых он основан.
    """

    email: str
    """Проверенный адрес в нормализованном виде (обрезанные пробелы, нижний регистр домена)."""

    status: EmailStatus
    """Итоговый вердикт."""

    statusRaw: str
    """
    Вердикт в исходном строковом виде ("valid", "catch-all", "do_not_mail", ...).
    Позволяет отличить значение, которого ещё нет в перечислении, от
    unknown.
    """

    subStatus: str | None
    """
    Уточнение вердикта: "mailbox_not_found", "disposable", "role_based", "greylisted" и т.п.
    Пусто, когда уточнения нет (обычно у чистого "valid"). Расшифровку см. в EmailSubStatusCatalog.
    """

    account: str | None
    """Часть адреса ДО «@» (локальная часть)."""

    domain: str | None
    """Часть адреса ПОСЛЕ «@» (домен)."""

    freeEmail: bool
    """true — адрес на бесплатном публичном почтовике (gmail.com, mail.ru, yandex.ru...)."""

    catchAllDomain: bool | None
    """
    true — домен настроен как catch-all (отвечает «валидно» на любой ящик), false — нет,
    null — определить не удалось.
    """

    didYouMean: str | None
    """
    Предполагаемое исправление опечатки в домене ("gmial.com" → "user@gmail.com").
    null, когда опечатки не видно. Отличный сигнал для формы регистрации.
    """

    domainAgeDays: int | None
    """Возраст домена в днях. null, если возраст неизвестен. Молодой домен — повод насторожиться."""

    smtpProvider: str | None
    """Почтовая платформа домена ("g-suite", "outlook", ...). null, если не определена."""

    mxFound: bool
    """true — у домена есть MX-запись (то есть он в принципе может принимать почту)."""

    mxRecord: str | None
    """Приоритетная MX-запись домена ("aspmx.l.google.com"). null, если MX не найдены."""

    activeInDays: str | None
    """
    Давность последней активности адреса ("30", "60", ..., "365+"). Признак доступен
    не для всех адресов; если сведений об активности нет — null.
    """

    activeFirstSeen: str | None
    """
    Дата первого зафиксированного сигнала активности. Как и activeInDays,
    доступна не для всех адресов — тогда null.
    """

    processedAtUtc: str | None
    """Момент, когда адрес был проверен (UTC). null, если время проверки неизвестно."""

    elapsedMs: int
    """Длительность обработки запроса в миллисекундах."""

    deliverable: bool
    """
    Можно ли безопасно писать на адрес. true только для valid:
    catch-all и unknown — неопределённость, остальное — явный запрет.
    """


__all__ = ["ApiError", "EmailStatus", "EmailValidationReport"]
