"""
Типы запросов и ответов сервиса «API AML-скоринга».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/aml_ru.json.
"""

from __future__ import annotations

from typing import TypedDict


class AmlCounterparty(TypedDict, total=False):
    """
    Контрагент кошелька — организация или адрес, с которым он связан напрямую или косвенно,
    с уровнем риска, категориями и денежными оборотами.
    """

    entityName: str | None
    """Название контрагента (например, имя биржи). "unknown" или пусто, если не атрибутирован."""

    entityType: str | None
    """Тип контрагента (например, "Exchange", "Mixer"). Пусто/"unknown", если неизвестен."""

    entitySubtype: str | None
    """Подтип контрагента. Пусто, если неизвестен."""

    riskLevel: str | None
    """Уровень риска контрагента: "low", "medium", "high", "severe" или "unknown" (не определён)."""

    categories: list[str]
    """Категории риска контрагента (например, ["mixer"], ["sanctioned"], ["unknown"])."""

    receivedUsd: float | None
    """Сколько получено ОТ контрагента в долларах США (если оценено). Иначе null."""

    sentUsd: float | None
    """Сколько отправлено контрагенту в долларах США (если оценено). Иначе null."""

    percentage: float
    """Доля контрагента в общей экспозиции кошелька (в процентах, 0–100)."""

    isDirect: bool
    """true, если связь прямая (без промежуточных адресов)."""

    country: str | None
    """Код страны контрагента (ISO-3166 alpha-2). Пусто, если неизвестен."""


class AmlFundExposure(TypedDict, total=False):
    """
    Одна строка экспозиции по средствам — где (по категории контрагента) кошелёк получал или
    отправлял средства, с долей и суммой. Используется и в sourceOfFunds,
    и в destinationOfFunds.
    """

    category: str | None
    """
    Категория контрагента (нормализованный код): например, "exchange_licensed" (лицензированная
    биржа), "mixer" (миксер), "darknet", "scam", "sanctioned", "gambling", "p2p". По ней видно,
    с каким типом сущностей связаны средства.
    """

    percentage: float
    """Доля этой категории в общей экспозиции (в процентах, 0–100)."""

    amountUsd: float | None
    """Сумма по этой строке экспозиции в долларах США (если оценена). Иначе null."""

    entityName: str | None
    """Название организации-контрагента (например, "Sideshift.ai"). Пусто, если неизвестно."""

    entityType: str | None
    """Тип организации (например, "Exchange", "Mixer", "Wallet"). Пусто, если неизвестен."""

    entitySubtype: str | None
    """Подтип организации (например, "Optional KYC and AML"). Пусто, если неизвестен."""

    hops: int | None
    """
    Число «прыжков» (hops) до контрагента: 0/1 — прямая связь, больше — косвенная (через
    промежуточные адреса). null, если не определено.
    """

    description: str | None
    """Человеко-читаемое описание строки экспозиции (например, "Exchange / Optional KYC")."""

    isDirect: bool
    """true, если это прямая связь (контрагент — непосредственный отправитель/получатель)."""

    exposureDirection: str | None
    """
    Направление экспозиции: "incoming" (средства пришли от контрагента) или "outgoing"
    (ушли к контрагенту). Дублирует принадлежность к Source/Destination, но удобно при
    объединении списков в одну таблицу.
    """

    exposureType: str | None
    """Тип экспозиции: "direct" (прямая) или "indirect" (косвенная, через цепочку адресов)."""

    country: str | None
    """Код страны контрагента в формате ISO-3166 alpha-2 (например, "KN"). Пусто, если неизвестен."""


class AmlNetworkEdge(TypedDict, total=False):
    """Ребро графа связей — перевод средств между двумя узлами AmlNetworkNode."""

    source: str | None
    """Идентификатор узла-источника перевода."""

    target: str | None
    """Идентификатор узла-получателя перевода."""

    amountUsd: float | None
    """Сумма перевода в долларах США (если оценена). Иначе null."""


class AmlNetworkNode(TypedDict, total=False):
    """
    Узел графа связей кошелька — адрес или организация в сети контактов. Содержит минимум,
    нужный для отрисовки графа; подробности по контрагентам — в AmlCounterparty.
    """

    id: str | None
    """Идентификатор узла (адрес или внутренний id сущности)."""

    label: str | None
    """Подпись узла для отображения (имя организации или сокращённый адрес)."""

    type: str | None
    """Тип узла (например, "exchange", "wallet", "mixer")."""

    riskLevel: str | None
    """Уровень риска узла ("low"/"medium"/"high"/"unknown")."""


class AmlScreeningRequest(TypedDict, total=False):
    """Параметры запроса AML-скрининга: адрес кошелька и сеть, в которой его проверять."""

    walletAddress: str
    """Адрес криптокошелька для проверки (обязателен)."""

    blockchain: str
    """
    Сеть (блокчейн) адреса: "BTC", "ETH", "BNB", "TRX", "SOL" и т.д. (обязательно).
    Должна входить в список поддерживаемых сетей AmlBlockchains.
    """


class AmlScreeningResult(TypedDict, total=False):
    """
    Полная карточка результата AML-скрининга криптокошелька одним плоским набором полей.
    Объединяет всё, что известно про адрес: нормализованный
    балл риска, уровень серьёзности, статус скрининга, разбивку источников и назначения средств
    по категориям, список контрагентов, флаги санкций/PEP и денежные обороты в USD.


    Пример. Для адреса 0x26a5...b216 в сети BNB: riskScore = 0,
    severity = "LOW", status = "SCREENED",
    sanctionsHit = false, а в destinationOfFunds — запись о
    лицензированной бирже со 100% исходящей экспозиции.
    """

    walletAddress: str
    """
    Проверённый адрес криптокошелька (в том виде, в котором по нему выполнялся скрининг).
    Для EVM-сетей это «0x…» + 40 hex-символов; для других сетей формат свой.
    """

    blockchain: str
    """
    Идентификатор сети (блокчейна), в которой выполнялся скрининг: например, "BTC", "ETH",
    "BNB", "TRX", "SOL". Полный список поддерживаемых сетей — см. AmlBlockchains.
    """

    screeningType: str
    """
    Тип скрининга. Для проверки кошелька всегда "WALLET_SCREENING". Поле оставлено в ответе,
    чтобы клиент мог единообразно различать режимы, если в будущем добавятся другие.
    """

    riskScore: int
    """
    Нормализованный балл риска от 0 до 100, где 0 — риск не обнаружен, 100 — максимальный риск.
    Это сводная оценка по всей экспозиции кошелька (источники/назначение средств, контрагенты,
    санкции). Для принятия решения удобнее опираться на severity — человеко-понятный
    уровень, выведенный из этого балла.
    """

    severity: str
    """
    Уровень серьёзности риска — человеко-понятная категория поверх riskScore.
    Возможные значения: "UNKNOWN" (недостаточно данных), "LOW" (низкий), "MEDIUM" (средний),
    "HIGH" (высокий), "CRITICAL" (критический). Удобно использовать для цветовой индикации и
    бизнес-правил (например, блокировать платёж при HIGH/CRITICAL).
    """

    status: str
    """
    Статус скрининга: "SCREENED" (проверка выполнена, результат готов), "PENDING" (поставлен
    в очередь — для on-demand обычно не встречается), "ERROR" (проверку выполнить не удалось).
    В норме при успешном ответе сервиса здесь "SCREENED".
    """

    summary: str | None
    """
    Краткая человеко-читаемая сводка результата (например, «Риск не обнаружен (0/100)»).
    Готова к показу пользователю как заголовок результата.
    """

    dominantRiskCategory: str | None
    """
    Доминирующая категория риска — категория с наибольшим вкладом в итоговый балл
    (например, "mixer", "sanctioned", "scam", "darknet"). null, если выраженной
    высокорисковой категории нет.
    """

    sanctionsHit: bool
    """
    true, если у кошелька обнаружена прямая или косвенная экспозиция на санкционные адреса/
    организации. Сильнейший стоп-сигнал: при true сделку, как правило, проводить нельзя.
    """

    pepCounterparty: bool
    """
    true, если среди контрагентов кошелька есть связь с публичным должностным лицом (PEP —
    Politically Exposed Person). Повод для усиленной проверки (enhanced due diligence).
    """

    totalValueUsd: float | None
    """Суммарный оборот кошелька в долларах США, если он оценён. Иначе null."""

    feeUsd: float | None
    """Суммарные комиссии по операциям кошелька в долларах США (если оценены). Иначе null."""

    sourceOfFunds: list[AmlFundExposure]
    """
    Источники средств — откуда на кошелёк приходили деньги, в разбивке по категориям
    контрагентов и долям. Помогает понять «происхождение» средств (source of funds).
    Пусто, если входящих операций нет или разбивка по ним недоступна.
    """

    destinationOfFunds: list[AmlFundExposure]
    """
    Назначение средств — куда с кошелька уходили деньги, в разбивке по категориям контрагентов
    и долям (destination of funds). Пусто, если исходящих операций нет или они не детализированы.
    """

    counterpartyConnections: list[AmlCounterparty]
    """
    Контрагенты кошелька — организации/адреса, с которыми он напрямую или косвенно связан,
    с уровнем риска, категориями и оборотами. Пусто, если связей не выявлено.
    """

    networkNodes: list[AmlNetworkNode]
    """
    Узлы графа связей кошелька (для визуализации сети контактов). Каждый узел — адрес/
    организация. Пусто, если граф связей по кошельку недоступен.
    """

    networkEdges: list[AmlNetworkEdge]
    """
    Рёбра графа связей кошелька — переводы между узлами networkNodes.
    Пусто, если граф связей по кошельку недоступен.
    """

    elapsedMs: int
    """Время выполнения запроса в миллисекундах."""


class AmlValidationResult(TypedDict, total=False):
    """
    Результат предварительной проверки входных данных — адреса и сети. Проверяются только
    поддержка сети и формат адреса, а НЕ существование адреса в блокчейне. Проверка бесплатна
    и позволяет отсеять заведомо некорректный ввод до платного скрининга.
    """

    normalizedAddress: str
    """Нормализованный адрес (убраны пробелы; для EVM-сетей приведён к нижнему регистру)."""

    normalizedBlockchain: str
    """Нормализованный код сети (верхний регистр), как он будет передан в скрининг."""

    isValid: bool
    """
    true, если входные данные прошли локальную проверку формата (сеть поддерживается, адрес
    непустой и правдоподобен по длине/составу). Это проверка ФОРМАТА, а не существования адреса.
    """

    message: str
    """Понятное человеку пояснение результата (что не так, либо «входные данные корректны»)."""


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


