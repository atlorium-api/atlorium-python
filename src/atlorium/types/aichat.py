"""
Типы запросов и ответов сервиса «API ИИ-чата».

Модели ответов — ``TypedDict`` (обычные ``dict``): новые поля сервера не ломают разбор.

СГЕНЕРИРОВАНО scripts/generate.py — не редактировать руками. Источник: spec/aichat_ru.json.
"""

from __future__ import annotations

from typing import TypedDict


class AiChatRequest(TypedDict, total=False):
    """
    Запрос на отправку сообщения в ИИ чат.
    Пользователь передаёт текст сообщения, опционально — идентификатор сессии
    для продолжения диалога и идентификатор (или алиас) модели.
    """

    message: str
    """Текст сообщения пользователя (обязательное поле; длина ограничена в зависимости от выбранной модели)."""

    sessionId: str | None
    """
    Идентификатор существующей сессии для продолжения диалога.
    Если null — сервис автоматически создаст новую сессию.
    """

    model: str | None
    """
    Идентификатор или алиас ИИ модели для обработки запроса.
    Если null — используется модель по умолчанию из конфигурации сервера.
    Список доступных моделей можно получить через GET /api/aichat/models.
    """


class AiChatResponse(TypedDict, total=False):
    """
    Ответ от ИИ чата. Содержит текст ответа модели, идентификатор сессии
    для продолжения диалога и статистику использования токенов.
    """

    sessionId: str
    """Идентификатор сессии — сохраните его для продолжения диалога."""

    reply: str
    """Текст ответа ИИ модели."""

    model: str
    """Идентификатор (или алиас) использованной модели."""

    promptTokens: int
    """Количество токенов, потраченных на промт (входные данные)."""

    completionTokens: int
    """Количество токенов, потраченных на генерацию ответа."""

    totalTokens: int
    """Общее количество использованных токенов (prompt + completion)."""

    createdAt: str
    """Время создания ответа в формате UTC."""


class AiChatSession(TypedDict, total=False):
    """
    Информация о сессии чата. Возвращается при запросе GET /api/aichat/session/{id}.
    Содержит метаданные сессии без самих сообщений.
    """

    sessionId: str
    """Уникальный идентификатор сессии."""

    messageCount: int
    """Количество сообщений пользователя в сессии (без ответов ИИ)."""

    createdAt: str
    """Время создания сессии (UTC)."""

    lastActivityAt: str
    """Время последней активности в сессии (UTC)."""


class AiModelInfo(TypedDict, total=False):
    """
    Описание одной доступной ИИ-модели: идентификатор для запросов, лимиты по токенам
    и цена токенов.
    """

    id: str
    """
    Идентификатор модели — его и нужно передавать в поле model запроса.
    Выглядит как короткое имя вида "fast" либо как полное имя модели.
    """

    name: str
    """Человекочитаемое название модели."""

    description: str
    """Описание возможностей и особенностей модели."""

    contextWindowTokens: int
    """
    Полное контекстное окно модели в токенах (вход + история + ответ).
    Справочное поле — например, у Gemini это может быть 1 000 000. НЕ путать
    с maxInputTokens: в одно сообщение влезает только его доля.
    """

    maxInputTokens: int
    """
    Лимит на ввод ОДНОГО сообщения пользователя в токенах. Это «живое»
    ограничение, по которому запрос и отклоняется: сообщение длиннее лимита
    получает 400. Значение заметно меньше contextWindowTokens —
    в окне модели должно остаться место под историю диалога и сам ответ.
    """

    maxOutputTokens: int
    """Потолок длины ответа модели в токенах (уходит в max_tokens запроса)."""

    maxTokens: int
    """
    Устаревшее поле: дублирует contextWindowTokens и оставлено для
    совместимости. В новых интеграциях используйте contextWindowTokens
    и maxInputTokens.
    """

    inputPricePer1kTokens: float
    """
    Цена ВХОДНЫХ токенов модели — в кредитах за 1000 токенов. Это ВТОРАЯ составляющая цены
    ИИ-запроса: первая (базовая ставка за сам запрос) едина для всех моделей и живёт в
    прайс-листе сервиса. 0 — модель бесплатна по токенам, клиент платит только за запрос.
    """

    outputPricePer1kTokens: float
    """
    Цена ВЫХОДНЫХ токенов (ответа модели) — в кредитах за 1000 токенов.
    См. inputPricePer1kTokens.
    """

    freeQuotaEligible: bool
    """
    Действует ли на эту модель бесплатная дневная квота. Квота гасит только базовую ставку
    за запрос, поэтому имеет смысл лишь у моделей с бесплатными токенами: для них запрос
    по квоте бесплатен ЦЕЛИКОМ. У платных моделей — false (оплата с первого запроса).
    """

    isAvailable: bool
    """
    Доступна ли модель для запросов. При false модель числится в каталоге, но
    обращения к ней отклоняются: она готовится к запуску. Поле стоит учитывать, чтобы
    не предлагать пользователю выбор, который заведомо не сработает.
    """

    isLocal: bool
    """
    Модель размещена на собственных серверах сервиса. Практический смысл один и
    важный: содержимое диалога с такой моделью не передаётся третьим лицам.
    """


class ApiError(TypedDict, total=False):
    """Единое тело ответа для любого отказа: и для ошибки валидации, и для отсутствующего ключа, и для исчерпанного лимита. Ветвиться в коде следует по полю `error` — это стабильный машинный код. Поля `title` и `message` предназначены человеку, их формулировки могут меняться."""

    error: str
    """
    Машинный код причины отказа. Возможные значения:

    * `server_error` (500) — Сервис временно недоступен
    * `unauthorized` (401) — Требуется вход
    * `api_key_required` (401) — Нужен API-ключ
    * `account_not_activated` (402) — Аккаунт не активирован
    * `rate_limited_client` (429) — Слишком много запросов
    * `rate_limited_global` (429) — Высокая нагрузка на сервис
    * `provider_keys_exhausted` (429) — Сервис временно недоступен
    * `insufficient_credits` (402) — Недостаточно кредитов
    * `guest_quota_exhausted` (402) — Бесплатный лимит на сегодня исчерпан
    * `service_disabled` (503) — Проводятся плановые работы
    * `maintenance` (503) — Проводятся плановые работы
    * `guest_not_allowed` (402) — Нужна регистрация
    * `service_not_in_account_terms` (403) — Сервис не подключён
    * `bad_request` (400) — Некорректный запрос
    * `forbidden` (403) — Доступ запрещён
    * `not_found` (404) — Ничего не найдено
    * `method_not_allowed` (405) — Метод HTTP не поддерживается
    * `unsupported_media_type` (415) — Формат запроса не поддерживается
    * `not_implemented` (501) — Режим пока не реализован
    """

    title: str
    """Короткий заголовок для интерфейса."""

    message: str
    """Подробное объяснение: что произошло и что с этим делать. Показывается пользователю целиком."""

    balance: float | None
    """Текущий баланс в кредитах. Заполняется при 402, чтобы не делать отдельный запрос за балансом; в остальных случаях null."""

    retryAfterSeconds: float | None
    """Через сколько секунд имеет смысл повторить запрос. Дублирует HTTP-заголовок Retry-After. null — если повтор не поможет (например, кончились кредиты)."""

    retryAfterText: str | None
    """Та же задержка готовой фразой — «через 2 мин 30 с». Чтобы клиентам не приходилось самим склонять минуты и секунды."""


